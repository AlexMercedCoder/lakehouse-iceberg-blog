#!/usr/bin/env node
/**
 * Writes 301s from every post's older URLs to its current /posts/<slug>/ URL,
 * plus fallbacks for archive and tag pages that no longer exist.
 *
 * Posts route by their `slug:` frontmatter. Before slugs were set, posts lived
 * at /posts/<file-name>/ (and /posts/<year>/<file-name>/); Google still crawls
 * those. This runs before every build, so new posts and slug changes are
 * covered automatically.
 *
 * The fallbacks have no `!`, so Netlify applies them only when no page exists
 * at the path: an archive page number that disappeared (/posts/61/) goes to
 * /posts/, a vanished tag page to that tag's first page, and a vanished tag to
 * /tags/. They never override a real page.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, basename, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BLOG = join(ROOT, 'src/content/blog');
const FILE = join(ROOT, 'public/_redirects');
const START = '# post-redirects:start (generated by scripts/build-post-redirects.mjs; do not edit)';
const END = '# post-redirects:end';

// Slugs that were published and later changed back; old URL -> current slug.
const RENAMED = {
  'dynamic-access-control-ai-agents': 'fine-grained-security-machine-speed-ai-agents',
  'ai-for-all-levels-1-what-ai-is-and-isnt': 'ai-for-all-levels-june-1-1-what-ai-is-and-isnt',
  'ai-for-all-levels-2-getting-started-for-free': 'ai-for-all-levels-june-1-2-getting-started-for-free',
  'ai-for-all-levels-3-chatgpt-and-claude-deep-dive': 'ai-for-all-levels-june-1-3-chatgpt-and-claude-deep-dive',
  'ai-for-all-levels-4-specialized-ai-tools': 'ai-for-all-levels-june-1-4-specialized-ai-tools',
  'ai-for-all-levels-5-going-advanced': 'ai-for-all-levels-june-1-5-going-advanced',
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : /\.mdx?$/.test(name) ? [full] : [];
  });
}

const rules = new Map();
const slugs = new Set();
for (const file of walk(BLOG)) {
  const fm = readFileSync(file, 'utf8').match(/^---\s*\n([\s\S]*?)\n---/)?.[1] ?? '';
  const slug = fm.match(/^slug:\s*["']?([^"'\n]+?)["']?\s*$/m)?.[1];
  if (!slug) continue;
  slugs.add(slug.toLowerCase());
  const target = `/posts/${slug.toLowerCase()}/`;
  const id = relative(BLOG, file).replace(/\.mdx?$/, '');
  // Netlify matches rules case-sensitively, so emit original-case and lowercase forms.
  for (const old of new Set([`/posts/${basename(id)}`, `/posts/${id}`].flatMap((p) => [p, p.toLowerCase()]))) {
    if (old !== target.slice(0, -1)) rules.set(old, target);
  }
}
for (const [old, slug] of Object.entries(RENAMED)) {
  if (slugs.has(slug.toLowerCase()) && !slugs.has(old)) rules.set(`/posts/${old}`, `/posts/${slug.toLowerCase()}/`);
}
// Never redirect away from a live post.
for (const from of [...rules.keys()]) if (slugs.has(from.replace('/posts/', '').toLowerCase()) && from === from.toLowerCase()) rules.delete(from);

const block = [
  START,
  `# ${rules.size} old post URL(s) -> current slug URLs`,
  ...[...rules].sort().map(([from, to]) => `${from}  ${to}  301!`),
  END,
].join('\n');

const FALLBACK_START = '# archive-fallbacks:start (generated; apply only when no page exists)';
const fallbacks = [
  FALLBACK_START,
  '/posts/:page  /posts/  301',
  '/tags/:tag/:page  /tags/:tag/  301',
  '/tags/:tag  /tags/  301',
  '# archive-fallbacks:end',
].join('\n');

const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
let text = readFileSync(FILE, 'utf8')
  .replace(new RegExp(`${escape(START)}[\\s\\S]*?${escape(END)}\\n?`), '')
  .replace(new RegExp(`${escape(FALLBACK_START)}[\\s\\S]*?# archive-fallbacks:end\\n?`), '');
const aliasEnd = '# alias-redirects:end\n';
text = text.includes(aliasEnd) ? text.replace(aliasEnd, `${aliasEnd}${block}\n`) : `${block}\n${text}`;
text = `${text.replace(/\n*$/, '\n')}${fallbacks}\n`;
writeFileSync(FILE, text);
console.log(`post-redirects: ${rules.size} post rules + archive fallbacks written to public/_redirects`);
